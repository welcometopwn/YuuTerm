import type { ITheme } from "@xterm/xterm";

/** App chrome colors; applied as CSS custom properties on the document. */
interface Chrome {
  text: string;
  chrome: string;
  side: string;
  surface: string;
  line: string;
  muted: string;
  accent: string;
  control: string;
  controlLine: string;
  field: string;
  primary: string;
  primaryLine: string;
}

export interface Theme {
  id: string;
  label: string;
  ui: Chrome;
  terminal: ITheme;
}

/** ANSI 0–15 in xterm.js order: normal then bright. */
const ansi = (c: string[]): ITheme => {
  const names = [
    "black",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "white",
  ];
  const theme: Record<string, string> = {};
  names.forEach((name, i) => {
    theme[name] = c[i];
    theme["bright" + name[0].toUpperCase() + name.slice(1)] = c[i + 8];
  });
  return theme as ITheme;
};

