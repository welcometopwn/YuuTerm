/** The saved theme id wins; older settings only carry the `mocha` flag. */
export const themeFor = (id: string, mocha: boolean): Theme =>
  themes.find((t) => t.id === id) ??
  themes.find((t) => t.id === (mocha ? "catppuccin-mocha" : "neutral"))!;

export const applyChrome = (theme: Theme) => {
  const root = document.documentElement.style;
  const vars: Record<keyof Chrome, string> = {
    text: "--text",
    chrome: "--chrome",
    side: "--side",
    surface: "--surface",
    line: "--line",
    muted: "--muted",
    accent: "--accent",
    control: "--control",
    controlLine: "--control-line",
    field: "--field",
    primary: "--primary",
    primaryLine: "--primary-line",
  };
  for (const [key, name] of Object.entries(vars))
    root.setProperty(name, theme.ui[key as keyof Chrome]);
};
